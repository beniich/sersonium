function buildServices(bp: RubriqueBlueprint): SensoriumServiceItem[] {
  return bp.serviceNames.map((name, idx) => {
    const slug = `${bp.id}-${idx + 1}`;
    const isDegraded = bp.id === 'calcul-silicium-edge' && idx === 3;
    const isStandby = idx === bp.serviceNames.length - 1 && bp.count >= 8;
    return {
      id: slug,
      name,
      endpoint: `/api/sensorium/${bp.id}/${idx + 1}`,
      status: isDegraded ? 'degraded' : isStandby ? 'standby' : 'online',
      latencyMs: 12 + ((idx * 17 + bp.count * 7) % 48),
      linkedAgentId: bp.linkedAgentId,
      summary: `${name} — ${bp.cluster}`,
    };
  });
}

